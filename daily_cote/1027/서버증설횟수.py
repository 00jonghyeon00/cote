players = [
    0, 2, 3, 3, 1, 2, 0, 0,
    0, 0, 4, 2, 0, 6, 0, 4,
    2, 13, 3, 5, 10, 0, 1, 5
]
m = 3
k = 5

# 3명이상 6명미만 추가서버 1대, 6명이상 9명미만 추가서버2대
# n=4 12명이상, 15명미만이면 추가서버가 최소 4대운영중
# n=3 9명이상, 12명 미만이면 추가서버가 최소 3대운영중
# 일반적으로 이용자가 6명이상, 9명 미만이면 추가 서버가 최소 2대 운영중, n =2
# n=1 3명이상, 6명미만이면 추가 서버가 최소 1대 운영중 
# n=0 0명이상, 3명미만이면 추가서버가 0대 운영중

# 0-1시, 이용자 0명 서버 0, 서버증설횟수 = 0
# 1-2시, 이용자 2명 서버 0, 서버증설횟수 = 0
# 2-3시, 이용자 3명 추가서버 1대, 2+5 까지운영, 서버증설횟수 = 1
# 3-4시, 이용자 3명 서버1, 
# 4-5시, 
# 10-11시, 이용자 4명, 서버 0->1 서버증설횟수 = 2, 10+5까지 운영
# 11-12시, 이용자 2명, 서버 1, 서버증설횟수 = 2, 10+5까지 운영
# 12-13시, 이용자 0명, 서버 1,
# 13-14시, 이용자 6명, 서버 1->2, 서버증설횟수 = 2+1, 서버1: 15까지운영, 서버2:13+5까지 운영
# 14-15시, 이용자 0명
# 15-16, 이용자 4명, 서버 1, 서버증설횟수 = 3, 서버2: 18까지 운영
# 16-17, 이용자 2명, 서버 1, 서버증설횟수 = 3, 서버2: 18
# 17-18, 이용자 13명, 서버 1->4, 서버증설횟수 = 3+3, 서버2 :18, 서버3개 : 17+5
# 18-19, 이용자 3명, 서버 3, 서버증설횟수 = 6, 서버3개 : 22
# 19-20, 이용자5, 서버 3, 서버증설횟수 =6, 서버3개 : 22
# 20-21, 이용자10, 서버 3, 서버증설횟수 6, ''
# 21-22, 0, 서버 3, ''
# 22-23, 1, 서버0
# 23-24, 5, 서버0->1, 서버증설횟수 = 6+1, 서버 1개: 

def solution(players, m, k):
    서버증설횟수 = 0
    서버운영 = []

    for 시간, 이용자수 in enumerate(players):
        while 시간 in 서버운영:
            서버운영.remove(시간)
        현재서버 = len(서버운영)
        n = 이용자수 // m
        
        if n > 현재서버:
            추가서버 = n - 현재서버
            for _ in range(추가서버):
                서버운영.append(시간+k)

            서버증설횟수 += 추가서버
    return 서버증설횟수

print(solution(players, m,k))